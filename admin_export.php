function pdfEscape(string $text): string
{
    $converted = iconv('UTF-8', 'Windows-1252//TRANSLIT//IGNORE', $text);
    if ($converted !== false) {
        $text = $converted;
    }
    $text = preg_replace('/[^\x20-\x7E\x80-\xFF]/', '?', $text) ?? '';
    return str_replace(["\\", '(', ')'], ["\\\\", '\(', '\)'], $text);
}

function pdfText(float $x, float $y, string $text, float $size = 9, bool $bold = false, string $color = '0.17 0.15 0.17'): string
{
    $font = $bold ? 'F2' : 'F1';
    return "q {$color} rg BT /{$font} {$size} Tf {$x} {$y} Td (" . pdfEscape($text) . ") Tj ET Q\n";
}

function pdfRect(float $x, float $y, float $width, float $height, string $color): string
{
    return "q {$color} rg {$x} {$y} {$width} {$height} re f Q\n";
}

function pdfWrap(string $value, int $maxCharacters, int $maxLines = 3): array
{
    $value = trim(preg_replace('/\s+/', ' ', (string)$value) ?? '');
    if ($value === '') {
        return ['—'];
    }
    $lines = explode("\n", wordwrap($value, max(1, $maxCharacters), "\n", true));
    if (count($lines) > $maxLines) {
        $lines = array_slice($lines, 0, $maxLines);
        $lines[$maxLines - 1] = rtrim(substr($lines[$maxLines - 1], 0, -3)) . '...';
    }
    return $lines;
}


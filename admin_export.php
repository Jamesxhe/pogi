    if ($output === false) {
        error_log('PUPick export failed to open output stream.');
        http_response_code(500);
        exit('Unable to create the export.');
    }
    foreach ($sheets as $sheet) {
        fputcsv($output, [$sheet['title']]);
        fputcsv($output, $sheet['headers']);
        foreach ($sheet['rows'] as $row) {
            $safeRow = array_map(static function ($value): string {
                $value = (string)($value ?? '');
                return preg_match('/^[\s]*[=+\-@]/u', $value) ? "'" . $value : $value;
            }, $row);
            fputcsv($output, $safeRow);
        }
        fputcsv($output, []);
    }
    fclose($output);
    exit;

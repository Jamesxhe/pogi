        if (!$section['rows']) {
            $commands .= pdfText($xStart + 4, $y - 14, 'No records available.', 9, false, '0.45 0.41 0.44');
        }
        $pages[count($pages) - 1] = $commands;
    }

    $objects = [
        1 => '<< /Type /Catalog /Pages 2 0 R >>',
        3 => '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        4 => '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
    ];
    $pageReferences = [];
    foreach ($pages as $index => $pageCommands) {
        $pageObject = 5 + ($index * 2);
        $contentObject = $pageObject + 1;
        $pageReferences[] = $pageObject . ' 0 R';
        $stream = "q\n" . $pageCommands . "Q\n";
        $objects[$pageObject] = '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 792 612]'
            . ' /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents '
            . $contentObject . ' 0 R >>';
        $objects[$contentObject] = '<< /Length ' . strlen($stream) . " >>\nstream\n"
            . $stream . "endstream";
    }
    $objects[2] = '<< /Type /Pages /Kids [' . implode(' ', $pageReferences)
        . '] /Count ' . count($pageReferences) . ' >>';
    ksort($objects);

    $pdf = "%PDF-1.4\n";
    $offsets = [0];
    $maxObject = max(array_keys($objects));
    for ($objectId = 1; $objectId <= $maxObject; $objectId++) {
        $offsets[$objectId] = strlen($pdf);
        $pdf .= $objectId . " 0 obj\n" . $objects[$objectId] . "\nendobj\n";
    }
    $xrefOffset = strlen($pdf);
    $pdf .= "xref\n0 " . ($maxObject + 1) . "\n0000000000 65535 f \n";
    for ($objectId = 1; $objectId <= $maxObject; $objectId++) {
        $pdf .= sprintf("%010d 00000 n \n", $offsets[$objectId]);
    }
    $pdf .= "trailer\n<< /Size " . ($maxObject + 1) . " /Root 1 0 R >>\n";
    $pdf .= "startxref\n" . $xrefOffset . "\n%%EOF";
    return $pdf;
}


function xmlText(string $value): string
{
    $value = preg_replace('/[\x00-\x08\x0B\x0C\x0E-\x1F]/', '', $value) ?? '';
    return htmlspecialchars($value, ENT_XML1 | ENT_QUOTES, 'UTF-8');
}

function excelColumn(int $number): string
{
    $column = '';
    while ($number > 0) {
        $number--;
        $column = chr(65 + ($number % 26)) . $column;
        $number = intdiv($number, 26);
    }
    return $column;
}

function worksheetXml(array $sheet, string $generatedAt, string $generatedBy): string
{
    $headers = $sheet['headers'];
    $rows = $sheet['rows'];
    $lastColumn = excelColumn(count($headers));
    $lastRow = count($rows) + 4;
    $xml = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>';
    $xml .= '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"';
    $xml .= ' xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">';
    $xml .= '<sheetViews><sheetView workbookViewId="0"><pane ySplit="4" topLeftCell="A5" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>';
    $xml .= '<sheetFormatPr defaultRowHeight="18"/><cols>';
    foreach ($sheet['widths'] as $index => $width) {
        $column = $index + 1;
        $xml .= '<col min="' . $column . '" max="' . $column . '" width="' . $width . '" customWidth="1"/>';
    }
    $xml .= '</cols><sheetData>';

    $writeRow = static function (int $rowNumber, array $values, int $style) use (&$xml): void {
        $xml .= '<row r="' . $rowNumber . '">';
        foreach ($values as $index => $value) {
            $reference = excelColumn($index + 1) . $rowNumber;
            if (is_int($value) || is_float($value)) {
                $xml .= '<c r="' . $reference . '" s="' . $style . '"><v>' . $value . '</v></c>';
            } else {
                $xml .= '<c r="' . $reference . '" s="' . $style . '" t="inlineStr"><is><t xml:space="preserve">'
                    . xmlText((string)($value ?? '')) . '</t></is></c>';
            }
        }
        $xml .= '</row>';
    };

    $writeRow(1, ['PUPick AI — Admin Operations Report'], 1);
    $writeRow(2, ['Generated ' . $generatedAt . ' · By ' . $generatedBy], 2);
    $writeRow(3, [], 0);
    $writeRow(4, $headers, 3);
    foreach ($rows as $index => $row) {
        $writeRow($index + 5, $row, 4);
    }

    $xml .= '</sheetData><mergeCells count="2"><mergeCell ref="A1:' . $lastColumn . '1"/>';
    $xml .= '<mergeCell ref="A2:' . $lastColumn . '2"/></mergeCells>';
    if ($rows) {
        $xml .= '<autoFilter ref="A4:' . $lastColumn . $lastRow . '"/>';
    }
    $xml .= '<pageMargins left="0.3" right="0.3" top="0.5" bottom="0.5" header="0.2" footer="0.2"/>';
    $xml .= '</worksheet>';
    return $xml;
}

function storedZip(array $files): string
{
    $body = '';
    $directory = '';
    $fileCount = 0;
    $dosTime = (int)(date('G') << 11 | date('i') << 5 | (int)(date('s') / 2));
    $dosDate = (int)(((int)date('Y') - 1980) << 9 | (int)date('n') << 5 | (int)date('j'));

    foreach ($files as $name => $contents) {
        $name = str_replace('\\', '/', (string)$name);
        $contents = (string)$contents;
        $nameLength = strlen($name);
        $size = strlen($contents);
        $crc = crc32($contents);
        $offset = strlen($body);
        $body .= pack('VvvvvvVVVvv', 0x04034b50, 20, 0, 0, $dosTime, $dosDate, $crc, $size, $size, $nameLength, 0);
        $body .= $name . $contents;
        $directory .= pack('VvvvvvvVVVvvvvvVV', 0x02014b50, 20, 20, 0, 0, $dosTime, $dosDate, $crc, $size, $size, $nameLength, 0, 0, 0, 0, 0, $offset);
        $directory .= $name;
        $fileCount++;
    }

    $directoryOffset = strlen($body);
    $body .= $directory;
    $body .= pack('VvvvvVVv', 0x06054b50, 0, 0, $fileCount, $fileCount, strlen($directory), $directoryOffset, 0);
    return $body;
}

